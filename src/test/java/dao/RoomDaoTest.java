package dao;

import entities.Room;
import java.util.List;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * CRUD and HQL tests for {@link RoomDao}.
 * The persistence unit points at an in-memory H2 database (see pom.xml).
 */
class RoomDaoTest {

    private static RoomDao dao;

    @BeforeAll
    static void setUp() {
        dao = new RoomDao();
    }

    @Test
    void createShouldPersistRoomAndGenerateId() {
        Room room = new Room("R-" + System.nanoTime(), "Network Lab");

        boolean created = dao.create(room);

        assertTrue(created, "Room creation must succeed");
        assertTrue(room.getId() > 0, "The identifier must be generated by the database");
    }

    @Test
    void getByIdShouldReturnThePersistedRoom() {
        Room room = new Room("R-" + System.nanoTime(), "Hardware Lab");
        dao.create(room);

        Room found = dao.getById(room.getId());

        assertNotNull(found);
        assertEquals(room.getCode(), found.getCode());
    }

    @Test
    void updateShouldModifyTheStoredLabel() {
        Room room = new Room("R-" + System.nanoTime(), "Old label");
        dao.create(room);

        room.setLabel("New label");
        assertTrue(dao.update(room));

        assertEquals("New label", dao.getById(room.getId()).getLabel());
    }

    @Test
    void deleteShouldRemoveTheRoom() {
        Room room = new Room("R-" + System.nanoTime(), "Temporary room");
        dao.create(room);

        assertTrue(dao.delete(room));
        assertNull(dao.getById(room.getId()));
    }

    @Test
    void getAllShouldReturnEveryRoom() {
        int before = dao.getAll().size();
        dao.create(new Room("R-" + System.nanoTime(), "Room A"));
        dao.create(new Room("R-" + System.nanoTime(), "Room B"));

        assertEquals(before + 2, dao.getAll().size());
    }

    @Test
    void findByCodePrefixShouldFilterOnTheCode() {
        String prefix = "PFX" + System.nanoTime();
        dao.create(new Room(prefix + "-1", "First"));
        dao.create(new Room(prefix + "-2", "Second"));
        dao.create(new Room("OTHER-" + System.nanoTime(), "Ignored"));

        List<Room> rooms = dao.findByCodePrefix(prefix);

        assertEquals(2, rooms.size());
        assertTrue(rooms.stream().allMatch(r -> r.getCode().startsWith(prefix)));
    }

    @Test
    void findRoomsWithMachinesShouldIgnoreEmptyRooms() {
        Room empty = new Room("EMPTY-" + System.nanoTime(), "No machine");
        dao.create(empty);

        boolean containsEmptyRoom = dao.findRoomsWithMachines().stream()
                .anyMatch(r -> r.getId() == empty.getId());

        assertFalse(containsEmptyRoom, "A room without machines must not be returned");
    }
}
